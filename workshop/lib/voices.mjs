//
// 背景（2026-10-03 主办方原话）：「风格似乎不太对，一直默认都是平实或者搞笑，没有其他多元素的风格」。
//   根因：开书方案 prompt 只让模型在「吐槽流 / 白描流」二选一，设定集「文风要求」也只给这两个选项，
//   所以不管选什么题材，写出来的笔调都是平实或搞笑。
// 设计：
//   - 题材（都市脑洞/悬疑灵异…）决定写什么；文风决定怎么写。两者自由组合。
//   - 默认 'auto' = 不注入任何东西，所有 prompt 与旧版逐字相同（回归测试盯着这条）。
//   - 每个文风 = 一句读者承诺 + 4–6 条可执行写法规则（句长、修辞、对白、叙述距离、情绪表达）+ 一条禁忌。
//     规则写成「能在正文里检查到」的形式，不写「要有文学性」这种空话。
//   - 星月写作的文风池（init.json `styles`）：辰东/猫腻/耳根/金庸/古代言情/幽默搞笑/放大矛盾和冲突/参考前文。
//     我们不用作者名（避免模仿在世作者），改成可描述的写法；「参考前文」对应 'follow'。

