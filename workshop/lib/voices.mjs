const BY_ID = new Map(VOICES.map((v) => [v.id, v]))

/** 统一入口：未知/空 → auto */
export function resolveVoice(id) {
  return BY_ID.get(String(id || '').trim()) || BY_ID.get(VOICE_DEFAULT)
}

/** 写手 prompt 段落；auto 返回空串（prompt 与旧版逐字相同） */
export function voiceBlock(id) {
  const v = resolveVoice(id)
  if (!v.rules.length) return ''
  return `【文风：${v.label}】（作者指定的笔调，和题材要求同时遵守；冲突时笔调听这里，情节听题材）\n${v.rules.map((r) => `- ${r}`).join('\n')}\n- 禁忌：${v.ban}\n\n`
}

/** 开书方案 / 设定集里的「风格：吐槽流 或 白描流」那一行替换成指定文风；auto 返回 null 表示不替换 */
export function voiceConceptLine(id) {
  const v = resolveVoice(id)
  if (!v.rules.length) return null
  return `风格：${v.label}（作者指定，方案的人物、冲突和语气都要长在这个文风上）`
}

export function publicVoices() {
  return VOICES.map((v) => ({ id: v.id, label: v.label, tagline: v.tagline }))
}
